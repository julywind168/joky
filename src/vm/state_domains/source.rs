pub(super) fn next_token() -> Result<u64, Error> {
    static NEXT: AtomicU64 = AtomicU64::new(1);
    NEXT.try_update(Ordering::Relaxed, Ordering::Relaxed, |n| {
        n.checked_add(1).filter(|n| *n <= u64::MAX / 2)
    })
    .map_err(|_| limited("Source domain identities exhausted"))
}
struct Owner {
    domain: Option<DomainOwner>,
    _charge: ExternalCharge,
}
// A snapshot owns copied result lanes and opaque versions, never the state root.
pub(super) struct Snapshot {
    pub(super) reads: reads::ReadSet,
    value: SnapshotValue,
    _charge: ExternalCharge,
}
enum SnapshotValue {
    Scalar(u64),
    Values(Vec<u64>),
}
unsafe extern "C" fn release_snapshot(token: *mut c_void) {
    drop(Box::from_raw(token.cast::<Snapshot>()));
}
fn adopt_snapshot(
    arena: &mut Arena,
    value: InstanceValue,
    reads: reads::ReadSet,
) -> Result<u64, Error> {
    adopt_snapshot_value(arena, SnapshotValue::Scalar(value.bits()), reads)
}
fn adopt_snapshot_value(
    arena: &mut Arena,
    value: SnapshotValue,
    reads: reads::ReadSet,
) -> Result<u64, Error> {
    let extra = match &value {
        SnapshotValue::Scalar(_) => 0,
        SnapshotValue::Values(words) => words.capacity() * std::mem::size_of::<u64>(),
    };
    let charge = arena.reserve_external(std::mem::size_of::<Snapshot>() + extra)?;
    let token = NonNull::new(
        Box::into_raw(Box::new(Snapshot {
            reads,
            value,
            _charge: charge,
        }))
        .cast(),
    )
    .unwrap();
    let resource = match OwnedResource::from_token(token, release_snapshot) {
        Ok(resource) => resource,
        Err(error) => {
            unsafe { release_snapshot(token.as_ptr()) };
            return Err(error);
        }
    };
    Ok(Buffer::external(arena, resource)?.as_ptr() as usize as u64)
}
unsafe extern "C" fn release(token: *mut c_void) {
    drop(Box::from_raw(token.cast::<Owner>()));
}
fn adopt(arena: &mut Arena, domain: DomainOwner) -> Result<u64, Error> {
    let charge = arena.reserve_external(std::mem::size_of::<Owner>())?;
    let token = NonNull::new(
        Box::into_raw(Box::new(Owner {
            domain: Some(domain),
            _charge: charge,
        }))
        .cast(),
    )
    .unwrap();
    let resource = match OwnedResource::from_token(token, release) {
        Ok(r) => r,
        Err(e) => {
            unsafe { release(token.as_ptr()) };
            return Err(e);
        }
    };
    Ok(Buffer::external(arena, resource)?.as_ptr() as usize as u64)
}
pub(super) fn module(
    registry: &Rc<RefCell<Domains>>,
    descriptor: u64,
) -> Result<(LoadedModule, usize), Error> {
    use crate::backends::{
        interp::BytecodeModule,
        jit::{CompiledFunction, CompiledModule},
    };
    let owner =
        crate::runtime::suspension::current_code().unwrap_or_else(|| Rc::new(()) as Rc<dyn Any>);
    if let Ok(module) = owner.clone().downcast::<CompiledModule>() {
        let key = Rc::as_ptr(&module) as usize;
        return Ok((LoadedModule::Jit(module), key));
    }
    if let Ok(module) = owner.clone().downcast::<BytecodeModule>() {
        let key = Rc::as_ptr(&module) as usize;
        return Ok((LoadedModule::Interpreter(module), key));
    }
    if descriptor == 0 {
        return Err(invalid(
            "Domain module requires a compiler-emitted descriptor",
        ));
    }
    if let Some(module) = registry
        .borrow()
        .entries
        .values()
        .find(|domain| domain.source_module == descriptor as usize)
        .map(|d| d.module.clone())
    {
        return Ok((module, descriptor as usize));
    }
    // This opaque module capability is generated by the compiler, not an integer
    // accepted from source. The active root/C caller retains its code allocation.
    let descriptor_ref =
        unsafe { &*(descriptor as usize as *const crate::runtime::domain::metadata::ModuleV3) };
    if descriptor_ref.version != 3 || descriptor_ref.count > 65536 {
        return Err(invalid("Invalid domain module descriptor"));
    }
    let entries =
        unsafe { std::slice::from_raw_parts(descriptor_ref.entries, descriptor_ref.count) };
    let mut records = HashMap::new();
    let mut exports = HashMap::new();
    let mut instances = HashMap::new();
    for entry in entries {
        let (name, info) =
            unsafe { crate::runtime::domain::metadata::decode(entry, &mut records) }?;
        let target = if info.suspends {
            &mut exports
        } else {
            &mut instances
        };
        target.insert(
            name,
            CompiledFunction {
                abi: crate::EntryAbi::Scalar,
                entry: entry.entry,
                info,
            },
        );
    }
    Ok((
        LoadedModule::Jit(Rc::new(CompiledModule::domain_module(
            exports, instances, owner,
        ))),
        descriptor as usize,
    ))
}
pub(super) fn handle(registry: &Rc<RefCell<Domains>>, token: u64) -> Result<DomainHandle, Error> {
    let handle = handle_identity(registry, token)?;
    registry.borrow().get(handle)?;
    Ok(handle)
}
// Observations may distinguish a quarantined domain from a closed one without
// obtaining access to its root. All actual accesses still go through `handle`.
pub(super) fn handle_identity(
    registry: &Rc<RefCell<Domains>>,
    token: u64,
) -> Result<DomainHandle, Error> {
    let domains = registry.borrow();
    let sequence = domains
        .entries
        .iter()
        .find(|(_, d)| d.source_token == token / 2)
        .map(|(id, _)| *id)
        .ok_or_else(|| invalid("Domain handle is closed or belongs to another executor"))?;
    let handle = DomainHandle {
        registry: domains.identity,
        sequence,
        writable: token & 1 != 0,
    };
    Ok(handle)
}
unsafe fn owner(frame: &CpsFrame) -> Result<crate::runtime::resource::ResourceLease, Error> {
    let pointer = (frame.slots[0] as usize as *mut Buffer)
        .as_mut()
        .ok_or_else(|| invalid("Null domain owner"))?;
    pointer.resource_mut()?.lease()
}
/// Move close responsibility without retaining the creating task or its arena.
///
/// # Safety
/// `pointer` must name a live source domain owner resource. The compiler-owned
/// adapter must hold its exclusive reference until this synchronous call returns.
pub(super) unsafe fn take_owner(pointer: u64) -> Result<DomainOwner, Error> {
    let lease = commits::lease(pointer)?;
    let owner = &mut *lease.token().cast::<Owner>();
    owner
        .domain
        .take()
        .ok_or_else(|| invalid("Domain owner was already transferred"))
}
pub(super) struct RequestOutput {
    pub layout: Option<(usize, usize)>,
    pub ty: Type,
    pub words: Vec<u64>,
    extra: Option<ResultCharge>,
}
struct ResultCharge {
    registry: Weak<RefCell<Domains>>,
    bytes: usize,
}
impl Drop for ResultCharge {
    fn drop(&mut self) {
        if let Some(registry) = self.registry.upgrade() {
            registry.borrow_mut().request_bytes -= self.bytes;
        }
    }
}
impl RequestOutput {
    pub(super) fn store(
        &mut self,
        registry: &Rc<RefCell<Domains>>,
        words: Vec<u64>,
    ) -> Result<(), Error> {
        if !crate::runtime::domain_packet::has_owners(&self.ty) {
            self.words.copy_from_slice(&words);
            return Ok(());
        }
        let extra = words
            .capacity()
            .saturating_sub(self.words.capacity())
            .checked_mul(8)
            .ok_or_else(|| limited("Domain result size overflow"))?;
        if extra != 0 {
            let mut domains = registry.borrow_mut();
            let bytes = domains
                .request_bytes
                .checked_add(extra)
                .filter(|n| *n <= domains.limits.max_request_bytes)
                .ok_or_else(|| limited("Domain request byte limit exceeded"))?;
            domains.request_bytes = bytes;
            self.extra = Some(ResultCharge {
                registry: Rc::downgrade(registry),
                bytes: extra,
            });
        }
        self.words = words;
        Ok(())
    }
}
pub(super) struct Completion {
    pub output: Option<RequestOutput>,
    pub result: Option<(RequestStatus, u64)>,
    pub published: bool,
    pub waiter: TaskWaker,
}
struct Receipt {
    domains: Weak<RefCell<Domains>>,
    charge: usize,
}
impl Receipt {
    fn reserve(registry: &Rc<RefCell<Domains>>, extra: usize) -> Result<Self, Error> {
        let mut domains = registry.borrow_mut();
        let charge = std::mem::size_of::<Wait>() + std::mem::size_of::<Completion>() + extra;
        let bytes = domains
            .request_bytes
            .checked_add(charge)
            .filter(|n| *n <= domains.limits.max_request_bytes)
            .ok_or_else(|| limited("Domain request byte limit exceeded"))?;
        if domains.requests.len() + domains.source_requests >= domains.limits.max_requests {
            return Err(limited("Domain request count limit exceeded"));
        }
        domains.source_requests += 1;
        domains.request_bytes = bytes;
        Ok(Self {
            domains: Rc::downgrade(registry),
            charge,
        })
    }
}
impl Drop for Receipt {
    fn drop(&mut self) {
        if let Some(domains) = self.domains.upgrade() {
            let mut domains = domains.borrow_mut();
            domains.source_requests -= 1;
            domains.request_bytes -= self.charge;
        }
    }
}
enum Wait {
    Turn(DomainRequest),
    Snapshot {
        request: DomainRequest,
        output: Option<Rc<RefCell<Vec<u64>>>>,
    },
    Request {
        _receipt: Receipt,
        executor: WeakExecutor,
        task: TaskId,
        result: Rc<RefCell<Completion>>,
    },
}
impl Drop for Wait {
    fn drop(&mut self) {
        if let Self::Request { executor, task, .. } = self {
            if let Some(executor) = executor.upgrade() {
                executor.cancel(*task);
                reap(&executor.domains());
            }
        }
    }
}
unsafe extern "C" fn stop(frame: *mut CpsFrame, _: u32) {
    let pointer = (*frame).host_context.cast::<Wait>();
    (*frame).host_context = std::ptr::null_mut();
    (*frame).host_stop = None;
    if !pointer.is_null() {
        drop(Box::from_raw(pointer));
    }
}
pub(super) fn same_module(a: &LoadedModule, b: &LoadedModule) -> bool {
    match (a, b) {
        (LoadedModule::Jit(a), LoadedModule::Jit(b)) => Rc::ptr_eq(a, b),
        (LoadedModule::Interpreter(a), LoadedModule::Interpreter(b)) => Rc::ptr_eq(a, b),
        _ => false,
    }
}
pub(super) fn scalar_argument(params: &[Type], bits: u64) -> Result<InstanceValue, Error> {
    if params.len() == 1 {
        if let Some(value) = InstanceValue::from_bits(&params[0], bits) {
            return Ok(value);
        }
    }
    Err(Error::new_with_code(
        crate::ErrorPhase::Runtime,
        crate::ErrorCode::InvalidCall,
        "Domain operation requires one valid scalar input",
    ))
}
pub(super) fn turn_arguments(
    info: &crate::core::ir::FunctionInfo,
    input: Option<u64>,
    write: bool,
) -> Result<Vec<InstanceValue>, Error> {
    if !instance::scalar(&info.signature.ret)
        || info
            .signature
            .params
            .first()
            .and_then(Type::reference_type)
            .is_none_or(|r| r.mutable != write)
        || info.signature.params.len() != 1 + usize::from(input.is_some())
    {
        return Err(Error::new_with_code(
            crate::ErrorPhase::Runtime,
            crate::ErrorCode::InvalidCall,
            "Domain operation signature does not match the access adapter",
        ));
    }
    input
        .map(|bits| scalar_argument(&info.signature.params[1..], bits))
        .transpose()
        .map(|value| value.into_iter().collect())
}
fn request_reply(frame: &mut CpsFrame, op: Operation, status: RequestStatus, bits: u64) -> u64 {
    if op == Operation::RequestValues {
        status as u64
    } else {
        reply(frame, status, bits)
    }
}
fn reply(frame: &mut CpsFrame, status: RequestStatus, bits: u64) -> u64 {
    // The private adapter has four parameter lanes followed by the tuple result.
    // No sentinel consumes a payload bit and no pointer escapes into caller storage.
    frame.slots[4] = status as u64;
    frame.slots[5] = bits;
    0
}
pub(super) fn request_info<'a>(module: &'a LoadedModule, name: &str) -> Option<&'a FunctionInfo> {
    match module {
        LoadedModule::Jit(module) => module.exports.get(name).map(|f| &f.info),
        LoadedModule::Interpreter(module) => crate::backends::interp::request_info(module, name),
    }
    .filter(|info| info.domain_request_entry)
}
fn request_input(module: &LoadedModule, name: &str, bits: u64) -> Result<InstanceValue, Error> {
    let info = request_info(module, name).ok_or_else(|| {
        Error::new_with_code(
            crate::ErrorPhase::Runtime,
            crate::ErrorCode::NotFound,
            "Unknown domain request entry",
        )
    })?;
    if !info.suspends || !instance::scalar(&info.signature.ret) {
        return Err(Error::new_with_code(
            crate::ErrorPhase::Runtime,
            crate::ErrorCode::InvalidCall,
            "Domain request requires a scalar suspending entry",
        ));
    }
    scalar_argument(&info.signature.params, bits)
}
unsafe fn wait(
    arena: &mut Arena,
    frame: &mut CpsFrame,
    registry: &Rc<RefCell<Domains>>,
    op: Operation,
) -> Result<Option<u64>, Error> {
    if frame.state == 0 {
        let wait = if matches!(
            op,
            Operation::SnapshotValues | Operation::SnapshotPairValues
        ) {
            let count = if op == Operation::SnapshotValues {
                1
            } else {
                2
            };
            let handles = (0..count)
                .map(|i| handle(registry, frame.slots[1 + i]))
                .collect::<Result<Vec<_>, _>>()?;
            let (module, _) = module(registry, frame.slots[0])?;
            let name = crate::runtime::owned_text::borrow(frame.slots[1 + count] as *const Buffer)?;
            let info = module.instance_info(name)?;
            if !info.domain_entry
                || !crate::core::state_domain::value_eligible(&info)
                || info.signature.params.len() != count
                || info
                    .signature
                    .params
                    .iter()
                    .any(|ty| ty.reference_type().is_none_or(|r| r.mutable))
            {
                return Err(invalid("Snapshot projection requires shared state references and a bounded pure-value result"));
            }
            let output = Rc::new(RefCell::new(vec![
                0;
                info.signature.ret.scalar_types().len()
            ]));
            let request = super::pairs::submit_values(
                registry,
                &handles,
                &module,
                name,
                Vec::new(),
                super::pairs::ValueOutput {
                    words: output.clone(),
                    snapshot: true,
                },
                crate::runtime::suspension::current_limits(),
            )?;
            request.register_current_wait()?;
            Wait::Snapshot {
                request,
                output: Some(output),
            }
        } else if matches!(op, Operation::Pair | Operation::SnapshotPair) {
            let handles = [
                handle(registry, frame.slots[1])?,
                handle(registry, frame.slots[2])?,
            ];
            let (module, _) = module(registry, frame.slots[0])?;
            let name = crate::runtime::owned_text::borrow(frame.slots[3] as *const Buffer)?;
            let info = module.instance_info(name)?;
            let types = info
                .signature
                .params
                .get(2..)
                .ok_or_else(|| invalid("Invalid pair signature"))?;
            if op == Operation::SnapshotPair
                && (info.signature.params.len() != 2
                    || info
                        .signature
                        .params
                        .iter()
                        .any(|ty| ty.reference_type().is_none_or(|r| r.mutable)))
            {
                return Err(invalid(
                    "Joint snapshot requires two shared state references",
                ));
            }
            let input = if types.is_empty() {
                Vec::new()
            } else {
                vec![scalar_argument(types, frame.slots[4])?]
            };
            let request = super::pairs::submit(
                registry,
                &handles,
                module,
                name,
                &input,
                crate::runtime::suspension::current_limits(),
            )?;
            request.register_current_wait()?;
            if op == Operation::SnapshotPair {
                Wait::Snapshot {
                    request,
                    output: None,
                }
            } else {
                Wait::Turn(request)
            }
        } else if matches!(
            op,
            Operation::CurrentRead | Operation::CurrentWrite | Operation::CurrentQuery
        ) {
            let name = crate::runtime::owned_text::borrow(frame.slots[0] as *const Buffer)?;
            let input = (op != Operation::CurrentRead).then(|| frame.slots[1]);
            let request = super::tasks::queue_current_scalar_call(
                name,
                input,
                op == Operation::CurrentWrite,
            )?;
            request.register_current_wait()?;
            Wait::Turn(request)
        } else {
            let handle = match handle(registry, frame.slots[1]) {
                Ok(h) => h,
                Err(e) => {
                    if matches!(op, Operation::Request | Operation::RequestValues) {
                        let domains = registry.borrow();
                        let failed = domains.entries.values().any(|d| {
                            d.source_token == frame.slots[1] / 2
                                && d.failure.is_some()
                                && !d.closing
                                && !domains.shutting_down
                        });
                        return Ok(Some(request_reply(
                            frame,
                            op,
                            if failed {
                                RequestStatus::DomainFailed
                            } else {
                                RequestStatus::Closed
                            },
                            0,
                        )));
                    }
                    return Err(e);
                }
            };
            let (module, _) = module(registry, frame.slots[0])?;
            let name = crate::runtime::owned_text::borrow(frame.slots[2] as *const Buffer)?;
            let request = matches!(op, Operation::Request | Operation::RequestValues);
            if !super::code::admits(
                &module,
                &registry.borrow().get(handle)?.module,
                name,
                request,
            ) {
                if request {
                    return Ok(Some(request_reply(
                        frame,
                        op,
                        RequestStatus::InvalidAccess,
                        0,
                    )));
                }
                return Err(Error::new_with_code(
                    crate::ErrorPhase::Runtime,
                    crate::ErrorCode::TypeMismatch,
                    "Domain operation does not match the code published for this state",
                ));
            }
            if request {
                let value_request = op == Operation::RequestValues;
                let prepared = (|| {
                    let info = request_info(&module, name)
                        .ok_or_else(|| invalid("Unknown domain request entry"))?;
                    let (input, output, extra) = if value_request {
                        if !info.suspends
                            || info.signature.params.len() != 1
                            || crate::core::script::domain_schema(&info.signature.params[0])
                                .is_none()
                            || crate::core::script::domain_schema(&info.signature.ret).is_none()
                        {
                            return Err(invalid("Invalid domain request value contract"));
                        }
                        let count = info.signature.ret.scalar_types().len();
                        // Reserve the retained result and the bounded extraction copy.
                        let packet = &*(frame.slots[3] as *const Buffer);
                        let extra = (packet.len() as usize
                            + usize::from(info.signature.params == [Type::Unit])
                            + 2 * count)
                            * std::mem::size_of::<u64>();
                        (None, Some((info.signature.ret.clone(), count)), extra)
                    } else {
                        (Some(request_input(&module, name, frame.slots[3])?), None, 0)
                    };
                    let receipt = Receipt::reserve(registry, extra)?;
                    let output = output.map(|(ty, count)| RequestOutput {
                        layout: None,
                        extra: None,
                        ty,
                        words: vec![0; count],
                    });
                    let completion = Rc::new(RefCell::new(Completion {
                        output,
                        result: None,
                        published: false,
                        waiter: current_waker()
                            .ok_or_else(|| invalid("Domain request requires an executor task"))?,
                    }));
                    let limits = crate::runtime::suspension::current_limits();
                    let task = if value_request {
                        let packet = &*(frame.slots[3] as *const Buffer);
                        let mut words = super::values::input_words(&info.signature.params, packet)?;
                        // Script frames encode Unit with zero packet lanes.
                        if info.signature.params == [Type::Unit] {
                            words.clear();
                        }
                        super::tasks::spawn_values(
                            registry,
                            handle,
                            name,
                            &words,
                            limits,
                            completion.clone(),
                        )?
                    } else {
                        super::tasks::spawn(
                            registry,
                            handle,
                            name,
                            &[input.unwrap()],
                            limits,
                            Some(completion.clone()),
                        )?
                    };
                    Ok::<_, Error>((receipt, completion, task))
                })();
                let (receipt, completion, task) = match prepared {
                    Ok(value) => value,
                    Err(error) => {
                        return Ok(Some(request_reply(
                            frame,
                            op,
                            RequestStatus::from_error(&error),
                            0,
                        )))
                    }
                };
                Wait::Request {
                    _receipt: receipt,
                    executor: registry.borrow().executor.clone(),
                    task,
                    result: completion,
                }
            } else {
                let info = module.instance_info(name)?;
                let args = turn_arguments(
                    &info,
                    matches!(op, Operation::Write | Operation::Query).then(|| frame.slots[3]),
                    op == Operation::Write,
                )?;
                let request = submit(
                    registry,
                    handle,
                    name,
                    &args,
                    crate::runtime::suspension::current_limits(),
                )?;
                request.register_current_wait()?;
                if op == Operation::Snapshot {
                    Wait::Snapshot {
                        request,
                        output: None,
                    }
                } else {
                    Wait::Turn(request)
                }
            }
        };
        frame.host_context = Box::into_raw(Box::new(wait)).cast();
        frame.host_stop = Some(stop);
        frame.state = 1;
        frame.wake = None;
        return Ok(None);
    }
    if frame.state != 1 || frame.host_context.is_null() {
        return Err(invalid("Invalid source domain wait state"));
    }
    let outcome = match &mut *frame.host_context.cast::<Wait>() {
        Wait::Snapshot { request, output } => {
            let Some((outcome, _, reads)) = request.take_snapshot_result() else {
                request.register_current_wait()?;
                return Ok(None);
            };
            match outcome {
                DomainOutcome::Value(value) => {
                    let reads = reads
                        .ok_or_else(|| invalid("Domain snapshot is missing read credentials"))?;
                    if let Some(output) = output {
                        let words = std::mem::take(&mut *output.borrow_mut());
                        adopt_snapshot_value(arena, SnapshotValue::Values(words), reads)
                    } else {
                        adopt_snapshot(arena, value, reads)
                    }
                }
                DomainOutcome::Failed(error) => Err(error),
                _ => Err(invalid("Domain snapshot was cancelled or closed")),
            }
        }
        Wait::Turn(request) => {
            let Some((outcome, rejection)) = request.take_access_result() else {
                request.register_current_wait()?;
                return Ok(None);
            };
            if let Some(rejection) = rejection {
                Ok(access::reply(frame, op, rejection.status(), 0))
            } else {
                match outcome {
                    DomainOutcome::Value(value) => Ok(access::reply(frame, op, 0, value.bits())),
                    DomainOutcome::Failed(e) => Err(e),
                    _ => Err(invalid("Domain operation was cancelled")),
                }
            }
        }
        Wait::Request { result, .. } => {
            let result = result.borrow();
            if !result.published {
                return Ok(None);
            }
            let (code, value) = result.result.unwrap();
            if code == RequestStatus::Completed {
                if let Some(output) = &result.output {
                    super::values::write_packet(
                        arena,
                        &mut *(frame.slots[3] as *mut Buffer),
                        &output.words,
                    )?;
                }
            }
            Ok(request_reply(frame, op, code, value))
        }
    };
    stop(frame, 0);
    outcome.map(Some)
}
pub(crate) unsafe fn poll(
    arena: &mut Arena,
    frame: &mut CpsFrame,
    op: Operation,
) -> Result<Option<u64>, Error> {
    let executor = crate::runtime::executor::current_executor()
        .ok_or_else(|| invalid("Domain operation requires an executor"))?;
    let registry = executor.domains();
    if frame.state == 0
        && !matches!(
            op,
            Operation::Values
                | Operation::CurrentValues
                | Operation::When
                | Operation::WhenPaths
                | Operation::AdmissionCreate
                | Operation::AdmissionHandle
                | Operation::AdmissionClose
                | Operation::AdmissionTry
                | Operation::AdmissionAcquire
                | Operation::AdmissionStatus
                | Operation::OutboxCreate
                | Operation::OutboxCreateDisconnect
                | Operation::OutboxHandle
                | Operation::OutboxClose
                | Operation::OutboxReceive
                | Operation::OutboxMessageClosed
                | Operation::OutboxMessageBytes
        )
        && !parallel::gate(frame)
    {
        return Ok(None);
    }
    if op.access() && op.status_payload() && !matches!(op, Operation::When | Operation::WhenPaths) {
        let initial = frame.state == 0;
        let result = match wait(arena, frame, &registry, op) {
            Err(error) if initial => {
                let rejection = access::source_rejection(&registry, frame, op, &error);
                Ok(Some(access::reply(frame, op, rejection.status(), 0)))
            }
            result => result,
        };
        if !matches!(result, Ok(None)) {
            stop(frame, 0);
        }
        if matches!(result, Ok(Some(_))) {
            frame.state = DONE;
        }
        return result;
    }
    let result = match op {
        Operation::TimerCreate
        | Operation::TimerHandle
        | Operation::TimerClose
        | Operation::TimerCancel
        | Operation::TimerStatus
        | Operation::PeriodicStatus
        | Operation::TimerStart
        | Operation::TimerStartValues => super::timers::poll(arena, frame, &registry, op)?,
        Operation::DirectoryCreate
        | Operation::DirectoryHandle
        | Operation::DirectoryClose
        | Operation::DirectoryInsert
        | Operation::DirectoryInsertOwned
        | Operation::DirectoryReplace
        | Operation::DirectoryRemove
        | Operation::DirectoryLookupNamed
        | Operation::DirectoryInsertNamed
        | Operation::DirectoryInsertOwnedNamed
        | Operation::DirectoryRemoveNamedIf
        | Operation::DirectoryRemoveNamed
        | Operation::DirectoryLookup
        | Operation::DirectoryFound => super::directory::poll(arena, frame, &registry, op)?,
        Operation::OutboxCreate
        | Operation::OutboxCreateDisconnect
        | Operation::OutboxHandle
        | Operation::OutboxClose
        | Operation::OutboxBatch
        | Operation::OutboxStage
        | Operation::OutboxReceive
        | Operation::OutboxAttach
        | Operation::OutboxAttachPair
        | Operation::OutboxAttachSet
        | Operation::OutboxMessageClosed
        | Operation::OutboxMessageBytes => {
            match super::outbox::poll(arena, frame, &registry, op)? {
                Some(value) => value,
                None => return Ok(None),
            }
        }
        Operation::Values | Operation::CurrentValues | Operation::When | Operation::WhenPaths => {
            return super::values::poll(arena, frame, &registry, op)
        }
        Operation::AdmissionCreate
        | Operation::AdmissionHandle
        | Operation::AdmissionClose
        | Operation::AdmissionTry
        | Operation::AdmissionAcquire
        | Operation::AdmissionStatus => {
            match super::admission::poll(arena, frame, &registry, op)? {
                Some(value) => value,
                None => return Ok(None),
            }
        }
        Operation::SetEditSnapshot
        | Operation::SetEditCandidate
        | Operation::AccessSet
        | Operation::AccessInclude
        | Operation::SnapshotSet
        | Operation::SetRead
        | Operation::SetReadValues
        | Operation::SetCheck
        | Operation::SetCandidate
        | Operation::SetCandidateValues
        | Operation::SetAdd
        | Operation::SetAddValues
        | Operation::CommitSet
        | Operation::CommitSetBefore
        | Operation::SetRevision => {
            match super::commits::sets::poll(arena, frame, &registry, op)? {
                Some(value) => value,
                None => return Ok(None),
            }
        }
        Operation::CandidateAt
        | Operation::CandidatePairAt
        | Operation::CandidateAtValues
        | Operation::CandidatePairAtValues
        | Operation::SetRevisionChecked
        | Operation::Candidate
        | Operation::CandidateValues
        | Operation::CandidatePair
        | Operation::CandidatePairValues
        | Operation::CommitPair
        | Operation::CommitPairBefore
        | Operation::CommitSecondRevision
        | Operation::Commit
        | Operation::CommitWait
        | Operation::CommitFailedOutbox
        | Operation::CommitRevision
        | Operation::CommitCancel
        | Operation::DeadlineAfter
        | Operation::CommitBefore
        | Operation::CommitIdentity => match super::commits::poll(arena, frame, &registry, op)? {
            Some(value) => value,
            None => return Ok(None),
        },
        Operation::Create | Operation::CreateValues => {
            let (module, key) = module(&registry, frame.slots[0])?;
            let name = crate::runtime::owned_text::borrow(frame.slots[1] as *const Buffer)?;
            let info = module.instance_info(name)?;
            let limits = crate::runtime::suspension::current_limits();
            let domain = if op == Operation::CreateValues {
                if !info.domain_entry || !crate::core::state_domain::constructor_eligible(&info) {
                    return Err(invalid("Invalid domain value constructor"));
                }
                let packet = &*(frame.slots[2] as *const Buffer);
                let words = super::values::input_words(&info.signature.params, packet)?;
                create_words(&registry, module, name, info, &words, limits)?
            } else {
                let input = scalar_argument(&info.signature.params, frame.slots[2])?;
                create(&registry, module, name, &[input], limits)?
            };
            registry
                .borrow_mut()
                .entries
                .get_mut(&domain.handle.sequence)
                .unwrap()
                .source_module = key;
            adopt(arena, domain)?
        }
        Operation::Handle => {
            let lease = owner(frame)?;
            let owner = &*lease.token().cast::<Owner>();
            let domains = registry.borrow();
            let handle = owner
                .domain
                .as_ref()
                .ok_or_else(|| invalid("Domain owner was already transferred"))?
                .handle;
            let domain = domains.get(handle)?;
            domain.source_token * 2 + 1
        }
        Operation::ReadOnly => {
            handle(&registry, frame.slots[0])?;
            frame.slots[0] & !1
        }
        Operation::Close => {
            let lease = owner(frame)?;
            let owner = &*lease.token().cast::<Owner>();
            let domain = owner
                .domain
                .as_ref()
                .ok_or_else(|| invalid("Domain owner was already transferred"))?;
            if !domain.close() {
                frame.wake = Some(crate::runtime::driver::Wake::Immediate);
                return Ok(None);
            }
            0
        }
        Operation::SnapshotReadValues => {
            let lease = owner(frame)?;
            let snapshot = &*lease.token().cast::<Snapshot>();
            let SnapshotValue::Values(words) = &snapshot.value else {
                return Err(invalid("Snapshot does not contain a value packet"));
            };
            super::values::write_packet(arena, &mut *(frame.slots[1] as *mut Buffer), words)?;
            0
        }
        Operation::SnapshotValue | Operation::SnapshotCheck => {
            let lease = owner(frame)?;
            let snapshot = &*lease.token().cast::<Snapshot>();
            if op == Operation::SnapshotValue {
                let SnapshotValue::Scalar(value) = snapshot.value else {
                    return Err(invalid("Snapshot does not contain a scalar"));
                };
                value
            } else {
                let domains = registry.borrow();
                match snapshot.reads.validate(&domains) {
                    Ok(()) => 0,
                    Err(commits::Status::Conflict) => 1,
                    Err(commits::Status::Closed) => 2,
                    Err(commits::Status::DomainFailed) => 3,
                    Err(_) => 4,
                }
            }
        }
        Operation::Request
        | Operation::RequestValues
        | Operation::Pair
        | Operation::SnapshotPair
        | Operation::Snapshot
        | Operation::SnapshotValues
        | Operation::SnapshotPairValues
        | Operation::Read
        | Operation::Write
        | Operation::CurrentRead
        | Operation::CurrentWrite
        | Operation::Query
        | Operation::CurrentQuery => match wait(arena, frame, &registry, op) {
            Ok(Some(value)) => value,
            Ok(None) => return Ok(None),
            Err(e) => {
                stop(frame, 0);
                return Err(e);
            }
        },
    };
    frame.state = DONE;
    Ok(Some(result))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn state_domains_snapshot_allocation_failures_refund_partial_adoption() {
        for record in [false, true] {
            let extra = if record {
                64 * std::mem::size_of::<u64>()
            } else {
                0
            };
            for limit in [0, std::mem::size_of::<Snapshot>() + extra] {
                let budget = std::sync::Arc::new(Budget {
                    limit: (limit).into(),
                    ..Default::default()
                });
                let mut arena = Arena::with_budget(budget.clone(), None);
                let handle = DomainHandle {
                    registry: 1,
                    sequence: 1,
                    writable: false,
                };
                let value = if record {
                    SnapshotValue::Values(vec![7; 64])
                } else {
                    SnapshotValue::Scalar(7)
                };
                let error = adopt_snapshot_value(
                    &mut arena,
                    value,
                    reads::ReadSet::single(handle, 0, 0, 0),
                )
                .unwrap_err();
                assert_eq!(error.code(), ErrorCode::ResourceLimit);
                assert_eq!(arena.bytes(), 0);
                assert_eq!(budget.bytes.get(), 0);
            }
        }
    }
}
