use std::{any::Any, ffi::c_void};
pub(super) fn next_token() -> Result<u64, Error> {
    static NEXT: AtomicU64 = AtomicU64::new(1);
    NEXT.try_update(Ordering::Relaxed, Ordering::Relaxed, |n| {
        n.checked_add(1).filter(|n| *n <= u64::MAX / 2)
    })
    .map_err(|_| limited("Source domain identities exhausted"))
}
struct Owner {
    domain: DomainOwner,
    _charge: ExternalCharge,
}
// A scalar snapshot owns its value and an opaque version, never the state root.
pub(super) struct Snapshot {
    pub(super) reads: reads::ReadSet,
    value: u64,
    _charge: ExternalCharge,
}
unsafe extern "C" fn release_snapshot(token: *mut c_void) {
    drop(Box::from_raw(token.cast::<Snapshot>()));
}
fn adopt_snapshot(
    arena: &mut Arena,
    value: InstanceValue,
    reads: reads::ReadSet,
) -> Result<u64, Error> {
    let charge = arena.reserve_external(std::mem::size_of::<Snapshot>())?;
    let token = NonNull::new(
        Box::into_raw(Box::new(Snapshot {
            reads,
            value: value.bits(),
            _charge: charge,
        }))
        .cast(),
    )
    .unwrap();
    let resource = match OwnedResource::from_token(token, release_snapshot) {
        Ok(resource) => resource,
        Err(error) => {
            unsafe { release_snapshot(token.as_ptr()) };
            return Err(error);
        }
    };
    Ok(Buffer::external(arena, resource)?.as_ptr() as usize as u64)
}
unsafe extern "C" fn release(token: *mut c_void) {
    drop(Box::from_raw(token.cast::<Owner>()));
}
fn adopt(arena: &mut Arena, domain: DomainOwner) -> Result<u64, Error> {
    let charge = arena.reserve_external(std::mem::size_of::<Owner>())?;
    let token = NonNull::new(
        Box::into_raw(Box::new(Owner {
            domain,
            _charge: charge,
        }))
        .cast(),
    )
    .unwrap();
    let resource = match OwnedResource::from_token(token, release) {
        Ok(r) => r,
        Err(e) => {
            unsafe { release(token.as_ptr()) };
            return Err(e);
        }
    };
    Ok(Buffer::external(arena, resource)?.as_ptr() as usize as u64)
}
pub(super) fn module(
    registry: &Rc<RefCell<Domains>>,
    descriptor: u64,
) -> Result<(LoadedModule, usize), Error> {
    use crate::backends::{
        interp::BytecodeModule,
        jit::{CompiledFunction, CompiledModule},
    };
    let owner =
        crate::runtime::suspension::current_code().unwrap_or_else(|| Rc::new(()) as Rc<dyn Any>);
    if let Ok(module) = owner.clone().downcast::<CompiledModule>() {
        let key = Rc::as_ptr(&module) as usize;
        return Ok((LoadedModule::Jit(module), key));
    }
    if let Ok(module) = owner.clone().downcast::<BytecodeModule>() {
        let key = Rc::as_ptr(&module) as usize;
        return Ok((LoadedModule::Interpreter(module), key));
    }
    if descriptor == 0 {
        return Err(invalid(
            "Domain module requires a compiler-emitted descriptor",
        ));
    }
    if let Some(module) = registry
        .borrow()
        .entries
        .values()
        .find(|domain| domain.source_module == descriptor as usize)
        .map(|d| d.module.clone())
    {
        return Ok((module, descriptor as usize));
    }
    // This opaque module capability is generated by the compiler, not an integer
    // accepted from source. The active root/C caller retains its code allocation.
    let descriptor_ref =
        unsafe { &*(descriptor as usize as *const crate::runtime::domain::metadata::ModuleV3) };
    if descriptor_ref.version != 3 || descriptor_ref.count > 65536 {
        return Err(invalid("Invalid domain module descriptor"));
    }
    let entries =
        unsafe { std::slice::from_raw_parts(descriptor_ref.entries, descriptor_ref.count) };
    let mut records = HashMap::new();
    let mut exports = HashMap::new();
    let mut instances = HashMap::new();
    for entry in entries {
        let (name, info) =
            unsafe { crate::runtime::domain::metadata::decode(entry, &mut records) }?;
        let target = if info.suspends {
            &mut exports
        } else {
            &mut instances
        };
        target.insert(
            name,
            CompiledFunction {
                abi: crate::EntryAbi::Scalar,
                entry: entry.entry,
                info,
            },
        );
    }
    Ok((
        LoadedModule::Jit(Rc::new(CompiledModule::domain_module(
            exports, instances, owner,
        ))),
        descriptor as usize,
    ))
}
pub(super) fn handle(registry: &Rc<RefCell<Domains>>, token: u64) -> Result<DomainHandle, Error> {
    let domains = registry.borrow();
    let sequence = domains
        .entries
        .iter()
        .find(|(_, d)| d.source_token == token / 2)
        .map(|(id, _)| *id)
        .ok_or_else(|| invalid("Domain handle is closed or belongs to another executor"))?;
    let handle = DomainHandle {
        registry: domains.identity,
        sequence,
        writable: token & 1 != 0,
    };
    domains.get(handle)?;
    Ok(handle)
}
unsafe fn owner(frame: &CpsFrame) -> Result<crate::runtime::resource::ResourceLease, Error> {
    let pointer = (frame.slots[0] as usize as *mut Buffer)
        .as_mut()
        .ok_or_else(|| invalid("Null domain owner"))?;
    pointer.resource_mut()?.lease()
}
pub(super) struct Completion {
    pub result: Option<(RequestStatus, u64)>,
    pub published: bool,
    pub waiter: TaskWaker,
}
struct Receipt {
    domains: Weak<RefCell<Domains>>,
    charge: usize,
}
impl Receipt {
    fn reserve(registry: &Rc<RefCell<Domains>>) -> Result<Self, Error> {
        let mut domains = registry.borrow_mut();
        let charge = std::mem::size_of::<Wait>() + std::mem::size_of::<Completion>();
        let bytes = domains
            .request_bytes
            .checked_add(charge)
            .filter(|n| *n <= domains.limits.max_request_bytes)
            .ok_or_else(|| limited("Domain request byte limit exceeded"))?;
        if domains.requests.len() + domains.source_requests >= domains.limits.max_requests {
            return Err(limited("Domain request count limit exceeded"));
        }
        domains.source_requests += 1;
        domains.request_bytes = bytes;
        Ok(Self {
            domains: Rc::downgrade(registry),
            charge,
        })
    }
}
impl Drop for Receipt {
    fn drop(&mut self) {
        if let Some(domains) = self.domains.upgrade() {
            let mut domains = domains.borrow_mut();
            domains.source_requests -= 1;
            domains.request_bytes -= self.charge;
        }
    }
}
enum Wait {
    Turn(DomainRequest),
    Snapshot {
        request: DomainRequest,
    },
    Request {
        _receipt: Receipt,
        executor: WeakExecutor,
        task: TaskId,
        result: Rc<RefCell<Completion>>,
    },
}
impl Drop for Wait {
    fn drop(&mut self) {
        if let Self::Request { executor, task, .. } = self {
            if let Some(executor) = executor.upgrade() {
                executor.cancel(*task);
                reap(&executor.domains());
            }
        }
    }
}
unsafe extern "C" fn stop(frame: *mut CpsFrame, _: u32) {
    let pointer = (*frame).host_context.cast::<Wait>();
    (*frame).host_context = std::ptr::null_mut();
    (*frame).host_stop = None;
    if !pointer.is_null() {
        drop(Box::from_raw(pointer));
    }
}
pub(super) fn same_module(a: &LoadedModule, b: &LoadedModule) -> bool {
    match (a, b) {
        (LoadedModule::Jit(a), LoadedModule::Jit(b)) => Rc::ptr_eq(a, b),
        (LoadedModule::Interpreter(a), LoadedModule::Interpreter(b)) => Rc::ptr_eq(a, b),
        _ => false,
    }
}
pub(super) fn scalar_argument(params: &[Type], bits: u64) -> Result<InstanceValue, Error> {
    if params.len() == 1 {
        if let Some(value) = InstanceValue::from_bits(&params[0], bits) {
            return Ok(value);
        }
    }
    Err(Error::new_with_code(
        crate::ErrorPhase::Runtime,
        crate::ErrorCode::InvalidCall,
        "Domain operation requires one valid scalar input",
    ))
}
pub(super) fn turn_arguments(
    info: &crate::core::ir::FunctionInfo,
    input: Option<u64>,
) -> Result<Vec<InstanceValue>, Error> {
    if !instance::scalar(&info.signature.ret)
        || info
            .signature
            .params
            .first()
            .and_then(Type::reference_type)
            .is_none_or(|r| r.mutable != input.is_some())
        || info.signature.params.len() != 1 + usize::from(input.is_some())
    {
        return Err(Error::new_with_code(
            crate::ErrorPhase::Runtime,
            crate::ErrorCode::InvalidCall,
            "Domain operation signature does not match the access adapter",
        ));
    }
    input
        .map(|bits| scalar_argument(&info.signature.params[1..], bits))
        .transpose()
        .map(|value| value.into_iter().collect())
}
fn reply(frame: &mut CpsFrame, status: RequestStatus, bits: u64) -> u64 {
    // The private adapter has four parameter lanes followed by the tuple result.
    // No sentinel consumes a payload bit and no pointer escapes into caller storage.
    frame.slots[4] = status as u64;
    frame.slots[5] = bits;
    0
}
pub(super) fn request_info<'a>(module: &'a LoadedModule, name: &str) -> Option<&'a FunctionInfo> {
    match module {
        LoadedModule::Jit(module) => module.exports.get(name).map(|f| &f.info),
        LoadedModule::Interpreter(module) => crate::backends::interp::request_info(module, name),
    }
}
fn request_input(module: &LoadedModule, name: &str, bits: u64) -> Result<InstanceValue, Error> {
    let info = request_info(module, name).ok_or_else(|| {
        Error::new_with_code(
            crate::ErrorPhase::Runtime,
            crate::ErrorCode::NotFound,
            "Unknown domain request entry",
        )
    })?;
    if !info.suspends || !instance::scalar(&info.signature.ret) {
        return Err(Error::new_with_code(
            crate::ErrorPhase::Runtime,
            crate::ErrorCode::InvalidCall,
            "Domain request requires a scalar suspending entry",
        ));
    }
    scalar_argument(&info.signature.params, bits)
}
unsafe fn wait(
    arena: &mut Arena,
    frame: &mut CpsFrame,
    registry: &Rc<RefCell<Domains>>,
    op: Operation,
) -> Result<Option<u64>, Error> {
    if frame.state == 0 {
        let wait = if matches!(op, Operation::Pair | Operation::SnapshotPair) {
            let handles = [
                handle(registry, frame.slots[1])?,
                handle(registry, frame.slots[2])?,
            ];
            let (module, _) = module(registry, frame.slots[0])?;
            let name = crate::runtime::owned_text::borrow(frame.slots[3] as *const Buffer)?;
            let info = module.instance_info(name)?;
            let types = info
                .signature
                .params
                .get(2..)
                .ok_or_else(|| invalid("Invalid pair signature"))?;
            if op == Operation::SnapshotPair
                && (info.signature.params.len() != 2
                    || info
                        .signature
                        .params
                        .iter()
                        .any(|ty| ty.reference_type().is_none_or(|r| r.mutable)))
            {
                return Err(invalid(
                    "Joint snapshot requires two shared state references",
                ));
            }
            let input = if types.is_empty() {
                Vec::new()
            } else {
                vec![scalar_argument(types, frame.slots[4])?]
            };
            let request = super::pairs::submit(
                registry,
                &handles,
                module,
                name,
                &input,
                crate::runtime::suspension::current_limits(),
            )?;
            request.register_current_wait()?;
            if op == Operation::SnapshotPair {
                Wait::Snapshot { request }
            } else {
                Wait::Turn(request)
            }
        } else if matches!(op, Operation::CurrentRead | Operation::CurrentWrite) {
            let name = crate::runtime::owned_text::borrow(frame.slots[0] as *const Buffer)?;
            let input = (op == Operation::CurrentWrite).then(|| frame.slots[1]);
            let request = super::tasks::queue_current_scalar_call(name, input)?;
            request.register_current_wait()?;
            Wait::Turn(request)
        } else {
            let handle = match handle(registry, frame.slots[1]) {
                Ok(h) => h,
                Err(e) => {
                    if op == Operation::Request {
                        let domains = registry.borrow();
                        let failed = domains.entries.values().any(|d| {
                            d.source_token == frame.slots[1] / 2
                                && d.failure.is_some()
                                && !d.closing
                                && !domains.shutting_down
                        });
                        return Ok(Some(reply(
                            frame,
                            if failed {
                                RequestStatus::DomainFailed
                            } else {
                                RequestStatus::Closed
                            },
                            0,
                        )));
                    }
                    return Err(e);
                }
            };
            let (module, _) = module(registry, frame.slots[0])?;
            let name = crate::runtime::owned_text::borrow(frame.slots[2] as *const Buffer)?;
            let request = op == Operation::Request;
            if !super::code::admits(
                &module,
                &registry.borrow().get(handle)?.module,
                name,
                request,
            ) {
                if request {
                    return Ok(Some(reply(frame, RequestStatus::InvalidAccess, 0)));
                }
                return Err(Error::new_with_code(
                    crate::ErrorPhase::Runtime,
                    crate::ErrorCode::TypeMismatch,
                    "Domain operation does not match the code published for this state",
                ));
            }
            if request {
                let receipt = match Receipt::reserve(registry) {
                    Ok(receipt) => receipt,
                    Err(error) => {
                        return Ok(Some(reply(frame, RequestStatus::from_error(&error), 0)))
                    }
                };
                let completion = Rc::new(RefCell::new(Completion {
                    result: None,
                    published: false,
                    waiter: current_waker()
                        .ok_or_else(|| invalid("Domain request requires an executor task"))?,
                }));
                let input = match request_input(&module, name, frame.slots[3]) {
                    Ok(input) => input,
                    Err(error) => {
                        return Ok(Some(reply(frame, RequestStatus::from_error(&error), 0)))
                    }
                };
                let task = match super::tasks::spawn(
                    registry,
                    handle,
                    name,
                    &[input],
                    crate::runtime::suspension::current_limits(),
                    Some(completion.clone()),
                ) {
                    Ok(task) => task,
                    Err(error) => {
                        return Ok(Some(reply(frame, RequestStatus::from_error(&error), 0)))
                    }
                };
                Wait::Request {
                    _receipt: receipt,
                    executor: registry.borrow().executor.clone(),
                    task,
                    result: completion,
                }
            } else {
                let info = module.instance_info(name)?;
                let args = turn_arguments(&info, (op == Operation::Write).then(|| frame.slots[3]))?;
                let request = submit(
                    registry,
                    handle,
                    name,
                    &args,
                    crate::runtime::suspension::current_limits(),
                )?;
                request.register_current_wait()?;
                if op == Operation::Snapshot {
                    Wait::Snapshot { request }
                } else {
                    Wait::Turn(request)
                }
            }
        };
        frame.host_context = Box::into_raw(Box::new(wait)).cast();
        frame.host_stop = Some(stop);
        frame.state = 1;
        frame.wake = None;
        return Ok(None);
    }
    if frame.state != 1 || frame.host_context.is_null() {
        return Err(invalid("Invalid source domain wait state"));
    }
    let outcome = match &mut *frame.host_context.cast::<Wait>() {
        Wait::Snapshot { request } => {
            let Some((outcome, _, reads)) = request.take_snapshot_result() else {
                request.register_current_wait()?;
                return Ok(None);
            };
            match outcome {
                DomainOutcome::Value(value) => {
                    let reads = reads
                        .ok_or_else(|| invalid("Domain snapshot is missing read credentials"))?;
                    adopt_snapshot(arena, value, reads)
                }
                DomainOutcome::Failed(error) => Err(error),
                _ => Err(invalid("Domain snapshot was cancelled or closed")),
            }
        }
        Wait::Turn(request) => {
            let Some(outcome) = request.take_result() else {
                request.register_current_wait()?;
                return Ok(None);
            };
            match outcome {
                DomainOutcome::Value(value) => Ok(value.bits()),
                DomainOutcome::Failed(e) => Err(e),
                _ => Err(invalid("Domain operation was cancelled or closed")),
            }
        }
        Wait::Request { result, .. } => {
            let result = result.borrow();
            if !result.published {
                return Ok(None);
            }
            let (code, value) = result.result.unwrap();
            Ok(reply(frame, code, value))
        }
    };
    stop(frame, 0);
    outcome.map(Some)
}
pub(crate) unsafe fn poll(
    arena: &mut Arena,
    frame: &mut CpsFrame,
    op: Operation,
) -> Result<Option<u64>, Error> {
    let executor = crate::runtime::executor::current_executor()
        .ok_or_else(|| invalid("Domain operation requires an executor"))?;
    let registry = executor.domains();
    let result = match op {
        Operation::TimerCreate
        | Operation::TimerHandle
        | Operation::TimerClose
        | Operation::TimerCancel
        | Operation::TimerStatus
        | Operation::TimerStart => super::timers::poll(arena, frame, &registry, op)?,
        Operation::DirectoryCreate
        | Operation::DirectoryHandle
        | Operation::DirectoryClose
        | Operation::DirectoryInsert
        | Operation::DirectoryReplace
        | Operation::DirectoryRemove
        | Operation::DirectoryLookup
        | Operation::DirectoryFound => super::directory::poll(arena, frame, &registry, op)?,
        Operation::OutboxCreate
        | Operation::OutboxHandle
        | Operation::OutboxClose
        | Operation::OutboxBatch
        | Operation::OutboxStage
        | Operation::OutboxReceive
        | Operation::OutboxAttach
        | Operation::OutboxAttachPair
        | Operation::OutboxAttachSet
        | Operation::OutboxMessageClosed
        | Operation::OutboxMessageBytes => {
            match super::outbox::poll(arena, frame, &registry, op)? {
                Some(value) => value,
                None => return Ok(None),
            }
        }
        Operation::Values | Operation::CurrentValues => {
            return super::values::poll(arena, frame, &registry, op == Operation::CurrentValues)
        }
        Operation::AdmissionCreate
        | Operation::AdmissionHandle
        | Operation::AdmissionClose
        | Operation::AdmissionTry
        | Operation::AdmissionAcquire
        | Operation::AdmissionStatus => {
            match super::admission::poll(arena, frame, &registry, op)? {
                Some(value) => value,
                None => return Ok(None),
            }
        }
        Operation::AccessSet
        | Operation::AccessInclude
        | Operation::SnapshotSet
        | Operation::SetRead
        | Operation::SetCheck
        | Operation::SetCandidate
        | Operation::SetAdd
        | Operation::CommitSet
        | Operation::CommitSetBefore
        | Operation::SetRevision => {
            match super::commits::sets::poll(arena, frame, &registry, op)? {
                Some(value) => value,
                None => return Ok(None),
            }
        }
        Operation::Candidate
        | Operation::CandidatePair
        | Operation::CommitPair
        | Operation::CommitPairBefore
        | Operation::CommitSecondRevision
        | Operation::Commit
        | Operation::CommitWait
        | Operation::CommitRevision
        | Operation::CommitCancel
        | Operation::DeadlineAfter
        | Operation::CommitBefore
        | Operation::CommitIdentity => match super::commits::poll(arena, frame, &registry, op)? {
            Some(value) => value,
            None => return Ok(None),
        },
        Operation::Create => {
            let (module, key) = module(&registry, frame.slots[0])?;
            let name = crate::runtime::owned_text::borrow(frame.slots[1] as *const Buffer)?;
            let input = scalar_argument(
                &module.instance_info(name)?.signature.params,
                frame.slots[2],
            )?;
            let domain = create(
                &registry,
                module,
                name,
                &[input],
                crate::runtime::suspension::current_limits(),
            )?;
            registry
                .borrow_mut()
                .entries
                .get_mut(&domain.handle.sequence)
                .unwrap()
                .source_module = key;
            adopt(arena, domain)?
        }
        Operation::Handle => {
            let lease = owner(frame)?;
            let owner = &*lease.token().cast::<Owner>();
            let domains = registry.borrow();
            let domain = domains.get(owner.domain.handle)?;
            domain.source_token * 2 + 1
        }
        Operation::ReadOnly => {
            handle(&registry, frame.slots[0])?;
            frame.slots[0] & !1
        }
        Operation::Close => {
            let lease = owner(frame)?;
            let owner = &*lease.token().cast::<Owner>();
            if !owner.domain.close() {
                frame.wake = Some(crate::runtime::driver::Wake::Immediate);
                return Ok(None);
            }
            0
        }
        Operation::SnapshotValue | Operation::SnapshotCheck => {
            let lease = owner(frame)?;
            let snapshot = &*lease.token().cast::<Snapshot>();
            if op == Operation::SnapshotValue {
                snapshot.value
            } else {
                let domains = registry.borrow();
                match snapshot.reads.validate(&domains) {
                    Ok(()) => 0,
                    Err(commits::Status::Conflict) => 1,
                    Err(commits::Status::Closed) => 2,
                    Err(commits::Status::DomainFailed) => 3,
                    Err(_) => 4,
                }
            }
        }
        Operation::Request
        | Operation::Pair
        | Operation::SnapshotPair
        | Operation::Snapshot
        | Operation::Read
        | Operation::Write
        | Operation::CurrentRead
        | Operation::CurrentWrite => match wait(arena, frame, &registry, op) {
            Ok(Some(value)) => value,
            Ok(None) => return Ok(None),
            Err(e) => {
                stop(frame, 0);
                return Err(e);
            }
        },
    };
    frame.state = DONE;
    Ok(Some(result))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn state_domains_snapshot_allocation_failures_refund_partial_adoption() {
        for limit in [0, std::mem::size_of::<Snapshot>()] {
            let budget = Rc::new(Budget {
                limit: Cell::new(limit),
                ..Default::default()
            });
            let mut arena = Arena::with_budget(budget.clone(), None);
            let handle = DomainHandle {
                registry: 1,
                sequence: 1,
                writable: false,
            };
            let error = adopt_snapshot(
                &mut arena,
                InstanceValue::Int32(7),
                reads::ReadSet::single(handle, 0, 0, 0),
            )
            .unwrap_err();
            assert_eq!(error.code(), ErrorCode::ResourceLimit);
            assert_eq!(arena.bytes(), 0);
            assert_eq!(budget.bytes.get(), 0);
        }
    }
}
